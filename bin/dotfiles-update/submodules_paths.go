//go:build ignore

package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"
)

const tmpl = `// Code generated by paths.go. DO NOT EDIT.
package main

var repos = []string{
{{- range $key, $path := . }}
	"{{ $path }}",
{{- end }}
}
`

func main() {
	paths, err := getSubmodulesFromConfig()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error fetching submodules paths: %v\n", err)
		os.Exit(1)
	}

	f, err := os.Create("paths_generated.go")
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error creating generated file: %v\n", err)
		os.Exit(1)
	}
	defer f.Close()

	t := template.Must(template.New("router").Parse(tmpl))
	if err := t.Execute(f, paths); err != nil {
		fmt.Fprintf(os.Stderr, "Error executing template: %v\n", err)
		os.Exit(1)
	}
}

func getSubmodulesFromConfig() ([]string, error) {
	cmd := exec.Command("git", "config", "--file", ".gitmodules", "--get-regexp", `\.path$`)
	cmd.Dir = "../.."

	output, err := cmd.Output()
	if err != nil {
		if exitError, ok := err.(*exec.ExitError); ok && exitError.ExitCode() == 1 {
			return nil, nil
		}
		return nil, err
	}

	var paths []string
	lines := strings.SplitSeq(strings.TrimSpace(string(output)), "\n")

	for line := range lines {
		if line == "" {
			continue
		}
		parts := strings.SplitN(line, " ", 2)
		if len(parts) == 2 {
			wd, err := os.Getwd()
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error obtaining the working directory: %v\n", err)
				os.Exit(1)
			}
			paths = append(paths, filepath.Join(filepath.Dir(filepath.Dir(wd)), parts[1]))
		}
	}
	return paths, nil
}
